def get_latest_news_csv():
    all_csvs = glob.glob("news_*.csv")
    valid_inputs = [f for f in all_csvs if not f.endswith("_fulltext.csv") and not f.endswith("_checkpoint.csv") and not f.endswith("_resolved.csv") and not f.endswith("_ranked.csv") and not f.endswith("_scrapes.csv")]
    if not valid_inputs:
        return None
    return max(valid_inputs, key=os.path.getmtime)

def resolve_url_via_brave(title):
    headers = {
        "Accept": "application/json",
        "Accept-Encoding": "gzip",
        "X-Subscription-Token": BRAVE_API_KEY
    }
    params = {"q": title, "count": 1}
    try:
        resp = requests.get(BRAVE_SEARCH_URL, headers=headers, params=params, timeout=10)
        if resp.status_code == 200:
            data = resp.json()
            results = data.get("web", {}).get("results", [])
            if results:
                return results[0].get("url")
    except Exception as e:
        print(f"⚠️ Brave Search API error for '{title[:40]}': {e}")
    return None

def resolve_urls(df, resolved_cache_file=None):
    if resolved_cache_file and os.path.exists(resolved_cache_file):
        print(f"📂 Found existing resolved URLs cache: {resolved_cache_file}. Loading...")
        df_cached = pd.read_csv(resolved_cache_file)
        if "Resolved_URL_via_BraveSearch" in df_cached.columns:
            return df_cached

    total = len(df)
    print(f"\n🔍 Starting Brave Search URL resolution for {total} articles...")
    resolved_links = []
    
    for idx, row in df.iterrows():
        title = row["Title"]
        existing_url = str(row.get("URL", ""))
        
        # If URL is already direct (not google redirection), keep it
        if existing_url.startswith("http") and "news.google.com" not in existing_url:
            resolved_links.append(existing_url)
            if (idx + 1) % 50 == 0 or idx == total - 1:
                print(f"➡️ ({idx+1}/{total}) Using direct URL: {existing_url[:65]}...")
            continue

        link = resolve_url_via_brave(title)
        if not link:
            link = existing_url
        resolved_links.append(link)
        if (idx + 1) % 25 == 0 or idx == total - 1:
            print(f"🔍 ({idx+1}/{total}) Resolved via Brave: \"{title[:45]}...\" -> {link[:65]}...")
        time.sleep(0.08) # Fast rate limit

    df["Resolved_URL_via_BraveSearch"] = resolved_links
    df["Resolved_URL_via_GoogleSearch"] = resolved_links
    df.drop_duplicates(subset=['Title'], keep='first', inplace=True)

    if resolved_cache_file:
        df.to_csv(resolved_cache_file, index=False, encoding='utf-8')
        print(f"💾 Saved resolved URLs cache to: {resolved_cache_file}")

    return df

async def extract_article_text_with_playwright(url, page):
    try:
        await page.goto(url, wait_until="domcontentloaded", timeout=20000)
        await page.wait_for_selector('body', timeout=6000)
        content = await page.content()

        soup = BeautifulSoup(content, "html.parser")
        for tag in soup(["script", "style", "header", "footer", "nav", "aside", "form", "img", "svg"]):
            tag.decompose()

        paragraphs = soup.find_all(["p", "div", "h1", "h2", "h3"])
        texts = [p.get_text().strip() for p in paragraphs if len(p.get_text().strip()) > 35]
        full_text = " ".join(texts)

        if len(full_text) > 100:
            return "SUCCESS", full_text
        else:
            return "FAILED", "Insufficient text extracted"
    except Exception as e:
        return "ERROR", str(e)

async def process_articles(df, checkpoint_file, max_workers=8):
    total = len(df)
    print(f"\n🚀 Starting Concurrent Playwright Extraction for {total} articles ({max_workers} workers)...")
    
    extracted_texts = [None] * total
    
    # Check if checkpoint exists
    if checkpoint_file and os.path.exists(checkpoint_file):
        try:
            df_cp = pd.read_csv(checkpoint_file)
            if "Extracted_Article_Text" in df_cp.columns:
                existing = df_cp["Extracted_Article_Text"].tolist()
                for i in range(min(len(existing), total)):
                    extracted_texts[i] = existing[i]
                resumed_count = sum(1 for x in extracted_texts if x is not None and not str(x).startswith("Failed:"))
                print(f"📂 Resuming from checkpoint: {resumed_count} already extracted.")
        except Exception as e:
            print(f"⚠️ Could not load checkpoint: {e}")

    sem = asyncio.Semaphore(max_workers)
    completed = sum(1 for x in extracted_texts if x is not None)
    lock = asyncio.Lock()

    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True)
        context = await browser.new_context(
            user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
        )

        async def worker(idx, target_url):
            nonlocal completed
            if extracted_texts[idx] is not None and not str(extracted_texts[idx]).startswith("Failed: ERROR"):
                return
            
            async with sem:
                page = await context.new_page()
                status, text = await extract_article_text_with_playwright(target_url, page)
                await page.close()

                async with lock:
                    if status == "SUCCESS":
                        extracted_texts[idx] = text
                        print(f"[{completed+1}/{total}] ✅ Extracted {len(text)} chars: {str(target_url)[:60]}...")
                    else:
                        extracted_texts[idx] = f"Failed: {status}. Reason: {text[:80]}. URL: {target_url}"
                        print(f"[{completed+1}/{total}] ❌ Failed ({status}): {str(target_url)[:60]}...")
                    completed += 1

                    if completed % 15 == 0 and checkpoint_file:
                        df_cp = df.copy()
                        df_cp["Extracted_Article_Text"] = extracted_texts
                        df_cp.to_csv(checkpoint_file, index=False, encoding='utf-8')

        tasks = []
        for idx, row in df.iterrows():
            target_url = row.get("Resolved_URL_via_BraveSearch") or row.get("URL")
            tasks.append(worker(idx, target_url))

        await asyncio.gather(*tasks)
        await browser.close()

    df["Extracted_Article_Text"] = extracted_texts
    return df

def main():
    args = get_args()
    input_file = args.input if args.input else get_latest_news_csv()
    
    if not input_file or not os.path.exists(input_file):
        print("❌ Error: No valid news CSV input file found to resolve.")
        sys.exit(1)

    print(f"=================================================================")
    print(f"🌐 Merlin Intelligence URL Resolution & Full-Text Extractor")
    print(f"📌 Input File: {input_file}")
    print(f"=================================================================")

    df = pd.read_csv(input_file)
    base_name = os.path.splitext(input_file)[0]
    resolved_file = f"{base_name}_resolved.csv"
    checkpoint_file = f"{base_name}_fulltext_checkpoint.csv"
    output_file = f"{base_name}_fulltext.csv"

    df_resolved = resolve_urls(df, resolved_file)

    df_final = asyncio.run(process_articles(df_resolved, checkpoint_file, max_workers=args.workers))
    df_final.to_csv(output_file, index=False, encoding='utf-8')

    if os.path.exists(checkpoint_file):
        try:
            os.remove(checkpoint_file)
        except:
            pass

    print(f"=================================================================")
    print(f"✅ Pipeline Resolution Complete!")
    print(f"💾 Full-text dataset saved to: '{output_file}'")
    print(f"=================================================================")

if __name__ == "__main__":
    main()
